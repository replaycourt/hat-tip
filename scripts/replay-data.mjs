// Derives web/js/replay-data.js, the compact data of the page's second replay, from the
// simulation's own files: sim/replay.json (the testnet house community, 36 rounds, the same gifts
// counted with the launch rules and with every dampening rule off) and sim/sweep.json (the
// colluders' excess in the 24-member community scenarios) and sim/params.json (the launch rules
// the replay applies). web/test/replay.test.mjs derives it
// again and fails if the module differs, so the page cannot drift from the simulation.
//
//   node scripts/replay-data.mjs          write web/js/replay-data.js
//   node scripts/replay-data.mjs --check  exit 1 if web/js/replay-data.js is not up to date
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const OUT = `${ROOT}web/js/replay-data.js`

const KIND = { '': 'honest', 'demo: colluding pair': 'pair', 'demo: free rider': 'free_rider' }
const isGuest = (a) => /^[0-9a-f]{64}$/.test(a)
const nameOf = (a) => a.split('.')[0].charAt(0).toUpperCase() + a.split('.')[0].slice(1)
const cents = (base) => Math.floor(Number(BigInt(base) / 10_000n)) // tUSD base units (6 decimals) to cents
const pts = (x) => Math.round(x * 10) / 10

/** The replay's data in the page's shape: per person and round, work, and cents paid both ways. */
export function derive(replay, sweep, params) {
  const people = replay.accounts.map((a) => ({ name: nameOf(a), kind: KIND[replay.labels[a]] ?? 'honest' }))
  people.push({ name: 'Visitors', kind: 'guests' })
  const index = new Map(replay.accounts.map((a, i) => [a, i]))
  const slot = (a) => (isGuest(a) ? people.length - 1 : index.get(a))
  const n = replay.rounds.length
  const grid = () => people.map(() => new Array(n).fill(0))
  const work = grid()
  const paid = { plain: grid(), rules: grid() }
  const struck = { plain: 0, rules: 0 }
  replay.rounds.forEach((row, r) => {
    // A free rider's note claims work it did not do; its work is 0. Visitors' work is not in the notes.
    for (const [a, items] of Object.entries(row.notes)) if (people[slot(a)].kind !== 'free_rider') work[slot(a)][r] += items
    for (const [side, key] of [['plain', 'none'], ['rules', 'launch']]) {
      for (const [receiver, amount, , status] of row[key].payouts ?? []) {
        if (status === 'paid') paid[side][slot(receiver)][r] += cents(amount)
        else struck[side]++
      }
    }
  })
  const a = sweep.stage_a
  const scenario = (label, key, field = 'excess') => ({ label, plain: pts(a.base.scenarios[key][field]), rules: pts(a.pick.scenarios[key][field]) })
  return {
    about: 'sim/replay.json, sim/sweep.json and sim/params.json, derived by scripts/replay-data.mjs',
    rounds: n,
    // the launch rules the replay applies (sim/params.json, testnet)
    rules: Object.fromEntries(['cap_per_receiver', 'reciprocal_bp', 'quadratic', 'breadth_k', 'breadth_bp', 'idle_bp', 'guest_weight_bp', 'guest_cap_bp', 'guest_receive_cap_bp'].map((k) => [k, params.testnet.config[k]])),
    people,
    work,
    paid,
    struck,
    scenarios: {
      members: 24,
      rounds: 52,
      seeds: 8,
      rows: [scenario('Colluding pair', 'pair'), scenario('Ring of three', 'ring3'), scenario('Ring of four', 'ring4'), scenario('Four free riders', 'free_riders', 'fr_excess')],
      honestPairCost: pts(a.pick.scenarios.honest.pair_loss),
    },
  }
}

export function moduleText(data) {
  return `// Generated by scripts/replay-data.mjs from sim/replay.json, sim/sweep.json and sim/params.json. Do not edit:
// web/test/replay.test.mjs derives it again and fails on any difference.
// Cents of tUSD paid per person and round with plain counting (every dampening rule off, the cap
// kept) and with the launch rules; work = items in the notes; scenario rows = colluders' excess
// payout share in percentage points (payout share minus work share), medians over the seeds.
export const REPLAY = ${JSON.stringify(data)}
`
}

export function load() {
  const replay = JSON.parse(readFileSync(`${ROOT}sim/replay.json`, 'utf8'))
  const sweep = JSON.parse(readFileSync(`${ROOT}sim/sweep.json`, 'utf8'))
  const params = JSON.parse(readFileSync(`${ROOT}sim/params.json`, 'utf8'))
  return derive(replay, sweep, params)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = moduleText(load())
  if (process.argv.includes('--check')) {
    const now = readFileSync(OUT, 'utf8')
    if (now !== text) {
      console.error('web/js/replay-data.js is out of date: run node scripts/replay-data.mjs')
      process.exit(1)
    }
    console.log('ok: web/js/replay-data.js matches sim/replay.json, sim/sweep.json and sim/params.json')
  } else {
    writeFileSync(OUT, text)
    console.log(`wrote web/js/replay-data.js (${text.length} bytes)`)
  }
}
